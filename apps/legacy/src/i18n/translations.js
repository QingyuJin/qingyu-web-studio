function translateDynamic(value, locale) {
  let match = value.match(/^(?:共 )?(\d+) 件作品$/)
  if (match) {
    if (locale === "en") return `${match[1]} Projects`
    if (locale === "ja") return `${match[1]}件の実績`
    return `포트폴리오 ${match[1]}개`
  }

  match = value.match(/^([\d\s]+) 元起$/)
  if (match) {
    if (locale === "en") return `From NT$${match[1]}`
    if (locale === "ja") return `NT$${match[1]}から`
    return `NT$${match[1]}부터`
  }

  match = value.match(/^(\d+\s+\d+)\s+(\d+\s+\d+) 元$/)
  if (match) {
    if (locale === "en") return `NT$${match[1]} to ${match[2]}`
    if (locale === "ja") return `NT$${match[1]}から${match[2]}`
    return `NT$${match[1]}에서 ${match[2]}`
  }

  match = value.match(/^([\d\s]+) 元以下$/)
  if (match) {
    if (locale === "en") return `Up to NT$${match[1]}`
    if (locale === "ja") return `NT$${match[1]}以下`
    return `NT$${match[1]} 이하`
  }

  match = value.match(/^([\d\s]+) 元$/)
  if (match) {
    return `NT$${match[1]}`
  }

  match = value.match(/^([\d\s]+) 天$/)
  if (match) {
    if (locale === "en") return `${match[1]} Days`
    if (locale === "ja") return `${match[1]}日`
    return `${match[1]}일`
  }

  match = value.match(/^約 ([\d\s]+) 週$/)
  if (match) {
    if (locale === "en") return `About ${match[1]} Weeks`
    if (locale === "ja") return `約${match[1]}週間`
    return `약 ${match[1]}주`
  }

  return null
}

export function translateDisplayText(value, locale) {
  if (locale === "zh-Hant" || !value.trim()) return value

  const leading = value.match(/^\s*/)?.[0] ?? ""
  const trailing = value.match(/\s*$/)?.[0] ?? ""
  const core = value.trim()

  if (/^\S+@\S+\.\S+$/.test(core) || /^https?:\/\//i.test(core)) return value
  if (!/[\u3400-\u9fff]/.test(core)) return value

  const exact = exactTranslations[core]?.[locale]
  const dynamic = translateDynamic(core, locale)
  const compact = Array.from(core.replace(/\s+/g, "")).length <= 8
  const semanticGroup = semanticGroups.find(({ test }) => test.test(core))
  const semantic = semanticGroup?.[compact ? "compact" : "value"]?.[locale]
  const translated = stripTranslatedPunctuation(exact || dynamic || semantic || (compact ? compactFallback[locale] : genericFallback[locale]))
  return `${leading}${translated}${trailing}`
}
