const registryBySlug = new Map(demoRegistry.map((demo) => [demo.slug, demo]))

export function getDemo(slug) {
  return registryBySlug.get(slug) ?? null
}

export function getDemoByPath(pathname) {
  return demoRegistry.find((demo) => pathname === demo.demoPath || pathname.startsWith(`${demo.demoPath}/`)) ?? null
}

export function demoContactPath(demo) {
  return `/contact?case=${encodeURIComponent(demo.contactCase)}&type=business-system`
}
