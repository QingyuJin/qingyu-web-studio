export const lineBotInboxMessages = lineBotScenarios
  .map((scenario, index) => {
    const sourceMessage = scenario.messages.find((message) => message.analysis)
    if (!sourceMessage) return null

    return {
      id: `inbox-${scenario.id}`,
      scenarioId: scenario.id,
      scenarioTitle: scenario.title,
      senderRole: sourceMessage.role,
      senderLabel: lineBotRoleLabels[sourceMessage.role],
      message: sourceMessage.text,
      time: sourceMessage.time,
      intent: sourceMessage.analysis.intent,
      status: inboxStatusByScenario[scenario.id] || "待處理",
      tags: scenario.tags,
      confidence: confidenceByIntent[sourceMessage.analysis.intent] || 90,
      entities: sourceMessage.analysis.entities,
      suggestedActions: sourceMessage.analysis.suggestedActions,
      backendActions: scenario.backendActions,
      buildFlowActions: lineBotBuildFlowActions[scenario.id] || [],
      actions: actionTemplates[scenario.id] || [
        { id: "update-case", type: "update_status", label: "更新案件狀態", nextStatus: "已更新進度", targetCaseId: "case-wang-waterproof" },
      ],
      parsedResult: {
        caseName: scenario.parsedCase.caseName,
        customerName: scenario.parsedCase.customer,
        location: scenario.parsedCase.location,
        projectType: scenario.parsedCase.type,
        status: scenario.parsedCase.status,
        missingFields: scenario.parsedCase.missingData,
        nextStep: scenario.parsedCase.nextStep,
        progress: scenario.parsedCase.progress,
      },
      sortOrder: index,
    }
  })
  .filter(Boolean)
